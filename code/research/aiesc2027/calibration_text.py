"""English Results draft for the calibration-split follow-up (Section 4.4.1, to follow Section 4.4).

Numbers are inserted from the result DataFrames; every directional statement is guarded by an assertion.
Output: outputs/aiesc2027/calibration_split/results/results_en_4_4_1.md and key_numbers.json.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import calibration_analysis as CA


def write(out: Path, iv, bs, prob, point, repro, scores):
    a90 = iv[iv.nominal == 0.9]

    def g(m, by="all", grp="all"):
        return a90[(a90.method == m) & (a90.group_by == by) & (a90.group == grp)].iloc[0]

    def b(m, s):
        return bs[(bs.method == m) & (bs.statistic == s)].iloc[0]

    def ci(m, s):
        r = b(m, s)
        return f"{r['estimate']:.3f} [95% CI {r['ci_low']:.3f}, {r['ci_high']:.3f}]"

    def rng(vals):
        lo, hi = f"{min(vals):.3f}", f"{max(vals):.3f}"
        return lo if lo == hi else f"{lo} to {hi}"

    conf = CA.CONFORMAL
    ngb_conf = [m for m in conf if m not in ("cqr_lightgbm", "split_abs_lightgbm")]
    pt = point.set_index("model")
    pr = prob.set_index("version")
    sc = scores.set_index("version")
    cov_all = {m: g(m)["coverage"] for m in CA.METHODS}
    wid = {m: g(m)["mean_width"] for m in CA.METHODS}
    low = {m: g(m, "grade_range", "0-59") for m in CA.METHODS}
    top = {m: g(m, "grade_range", "90-100")["coverage"] for m in CA.METHODS}
    cat_min = {m: a90[(a90.method == m) & (a90.group_by == "course_category")]["coverage"].min() for m in CA.METHODS}
    cat_max = {m: a90[(a90.method == m) & (a90.group_by == "course_category")]["coverage"].max() for m in CA.METHODS}
    prange = {m: a90[(a90.method == m) & (a90.group_by == "predicted_range")]["coverage"] for m in CA.METHODS}
    d_iso = bs[(bs.method == "refit_isotonic - refit_raw")].iloc[0]
    d_pl = bs[(bs.method == "refit_platt - refit_raw")].iloc[0]

    # ---- guards ----------------------------------------------------------------------------------------------
    assert all(b(m, "coverage90_all")["ci_low"] <= 0.9 <= b(m, "coverage90_all")["ci_high"] or cov_all[m] >= 0.9
               for m in conf), "a conformal method is below nominal"
    assert all(wid[m] < wid["ngb_raw"] for m in conf) and cov_all["ngb_raw"] > 0.9
    assert all(low[m]["coverage"] < 0.7 for m in CA.METHODS)
    assert max(conf, key=lambda m: low[m]["coverage"]) == "cqr_lightgbm"
    assert min(conf, key=lambda m: top[m]) == "cqr_lightgbm"
    assert all(low[m]["share_actual_below_interval"] > 0.9 * (1 - low[m]["coverage"]) for m in CA.METHODS)
    assert cat_min["mondrian_category"] > cat_min["split_norm"]
    assert prange["mondrian_predicted_range"].min() >= 0.85 and prange["cqr_lightgbm"].min() >= 0.85
    assert prange["split_abs"].min() < 0.75 and prange["split_abs_lightgbm"].min() < 0.75
    assert d_iso["ci_high"] < 0 and d_pl["ci_high"] < 0
    assert abs(pr.loc["refit_isotonic", "mean_predicted_probability"] - pr.loc["refit_isotonic", "prevalence"]) < 0.01
    assert pr.loc["refit_raw", "brier_skill_score"] < 0 < pr.loc["refit_isotonic", "brier_skill_score"]
    assert abs(pr.loc["refit_isotonic", "pr_auc"] - pr.loc["refit_raw", "pr_auc"]) < 0.01
    assert (repro["lightgbm_max_abs_diff"] == 0).all()

    ngb0 = pt.loc["NGBoost, original (full training fold)"]
    ngbr = pt.loc["NGBoost, reproduction refit (full training fold)"]
    ngb8 = pt.loc["NGBoost, proper-training refit (80%)"]
    lgb0 = pt.loc["LightGBM, original (full training fold)"]
    lgb8 = pt.loc["LightGBM, proper-training refit (80%)"]
    below_share = [low[m]["share_actual_below_interval"] / (1 - low[m]["coverage"]) for m in CA.METHODS]
    miss_text = ("every missed low-grade case lay below its interval (actual grade under the lower bound)"
                 if min(below_share) > 0.9995 else
                 f"{100 * min(below_share):.1f}% or more of missed low-grade cases lay below their interval")
    n_cal = repro["partition_cal_students"].astype(int)
    n_students = f"{n_cal.min():,d}" if n_cal.min() == n_cal.max() else f"{n_cal.min():,d} to {n_cal.max():,d}"
    text = f"""<!-- Generated by research/aiesc2027/run_calibration.py; design: research/aiesc2027/calibration_split_spec.json -->
### 4.4.1 Follow-up: Intervals and Risk Probabilities with an In-Fold Calibration Set

The cross-fold conformal intervals in Section 4.4 had no independent calibration set. In an exploratory follow-up whose
design was fixed before fitting, each student-split training fold was divided by student into a proper-training part
(80% of its students) and a calibration part (20%; {n_students} students per fold; the partition also used in
Section 4.2.1). NGBoost,
LightGBM and eight LightGBM quantile models (alpha 0.025 to 0.975) were refitted on the proper-training part only, and
every conformal quantile and probability-recalibration map for a test fold was computed from that fold's calibration
students. A reproduction check on the full training folds reproduced LightGBM's saved predictions exactly and
NGBoost's approximately (MAE {ngbr['MAE']:.3f} vs {ngb0['MAE']:.3f}; NGBoost's in-fold target encoder uses grouped inner
folds, which could not be reconstructed exactly on this hardware). Training on 80% of each fold cost little point
accuracy (MAE: NGBoost {ngb0['MAE']:.3f} to {ngb8['MAE']:.3f}; LightGBM {lgb0['MAE']:.3f} to {lgb8['MAE']:.3f}; NGBoost NLL
{sc.loc['original_full_fold_raw', 'NLL']:.3f} to {sc.loc['refit_80pct_raw', 'NLL']:.3f}).

Table 6 and Figure 6 report the nominal 90% intervals. The raw Normal intervals of the refitted NGBoost again
over-covered ({ci('ngb_raw', 'coverage90_all')}; mean width {wid['ngb_raw']:.3f} points). All six split-conformal
methods reached nominal marginal coverage ({rng([cov_all[m] for m in conf])}) with narrower intervals (mean width
{rng([wid[m] for m in conf])} points). Coverage within groups that are observable at prediction time could also be
controlled: Mondrian calibration by course category raised the lowest category coverage from
{cat_min['split_norm']:.3f} (pooled normalised conformal) to {cat_min['mondrian_category']:.3f} (range
{rng([cat_min['mondrian_category'], cat_max['mondrian_category']])}), and Mondrian calibration by predicted grade range
and CQR kept coverage at {rng(list(prange['mondrian_predicted_range']) + list(prange['cqr_lightgbm']))} in every
predicted grade range, whereas constant-width intervals around NGBoost or LightGBM covered only
{rng([prange['split_abs'].min(), prange['split_abs_lightgbm'].min()])} of enrolments predicted below 60.

None of these methods repaired coverage by actual grade. For enrolments whose actual grade was below 60, 90%-interval
coverage was {rng([low[m]['coverage'] for m in conf])} across the conformal methods and {low['ngb_raw']['coverage']:.3f} for
the raw Normal intervals, and {miss_text}. CQR gave the highest low-grade coverage ({ci('cqr_lightgbm', 'coverage90_actual_0_59')}) but the lowest coverage
in the 90–100 range ({top['cqr_lightgbm']:.3f}). This pattern is expected: split conformal guarantees coverage on
average over exchangeable students, not conditional on the unknown outcome, and the systematic overestimation of low
grades (Section 4.3) places low outcomes below intervals that are centred too high.

Recalibration on the calibration set did correct the risk probabilities (Table 7). The raw P(Y < 60) of the refitted
NGBoost averaged {pr.loc['refit_raw', 'mean_predicted_probability']:.3f} against a prevalence of
{pr.loc['refit_raw', 'prevalence']:.3f} (Brier skill score {pr.loc['refit_raw', 'brier_skill_score']:.3f}; ECE
{pr.loc['refit_raw', 'ece_10_bins']:.3f}). Isotonic recalibration brought the mean to
{pr.loc['refit_isotonic', 'mean_predicted_probability']:.3f}, lowered the Brier score by
{-d_iso['estimate']:.3f} (95% CI {-d_iso['ci_high']:.3f} to {-d_iso['ci_low']:.3f}) to a skill score of
{pr.loc['refit_isotonic', 'brier_skill_score']:.3f}, and reduced ECE to {pr.loc['refit_isotonic', 'ece_10_bins']:.3f};
logistic recalibration gave similar results (skill score {pr.loc['refit_platt', 'brier_skill_score']:.3f}; ECE
{pr.loc['refit_platt', 'ece_10_bins']:.3f}). Because both maps are monotone, ranking quality was essentially unchanged
(PR-AUC {pr.loc['refit_raw', 'pr_auc']:.3f} vs {pr.loc['refit_isotonic', 'pr_auc']:.3f}; ROC-AUC
{pr.loc['refit_raw', 'roc_auc']:.3f} vs {pr.loc['refit_isotonic', 'roc_auc']:.3f}). An in-fold calibration set therefore
makes NGBoost's risk probabilities usable as calibrated estimates, but it does not add discrimination: identifying more
low-grade enrolments requires better predictive information, not recalibration.

These follow-up results use refitted models trained on 80% of each training fold, the same semester as all other
analyses, and student-level exchangeability as the basis of the conformal guarantee; they are exploratory and are not
an independent validation.
"""
    out.mkdir(parents=True, exist_ok=True)
    (out / "results_en_4_4_1.md").write_text(text, encoding="utf-8")
    key = {"coverage90_all": cov_all, "mean_width90_all": wid,
           "coverage90_actual_0_59": {m: float(low[m]["coverage"]) for m in CA.METHODS},
           "coverage90_actual_90_100": top, "min_category_coverage90": cat_min,
           "min_predicted_range_coverage90": {m: float(prange[m].min()) for m in CA.METHODS},
           "probability": prob.set_index("version")[["mean_predicted_probability", "brier", "brier_skill_score",
                                                      "ece_10_bins", "pr_auc", "roc_auc"]].to_dict(orient="index"),
           "point_accuracy": point.set_index("model")[["MAE", "RMSE", "recall"]].to_dict(orient="index")}
    (out / "key_numbers.json").write_text(json.dumps(key, indent=2, default=float), encoding="utf-8")
