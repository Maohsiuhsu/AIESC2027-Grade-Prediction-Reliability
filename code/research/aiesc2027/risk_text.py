"""English Results draft for follow-up 2 (Sections 4.2.1 and 4.2.2, to follow Section 4.2).

Numbers are inserted from the result DataFrames; every directional statement is guarded by an assertion.
Output: outputs/aiesc2027/risk_methods/results/results_en_4_2_1_4_2_2.md and key_numbers.json.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import risk_analysis as R


def write(out: Path, evA, evB, con, probA, nonzero, zero_share, n_zero):
    a = evA["metrics"].set_index(["method", "operating_point"])
    b = evB["metrics"].set_index(["method", "operating_point"])
    nz = nonzero.set_index(["method", "operating_point"])
    thr = evA["thr"].groupby("method")
    c = con.set_index("contrast")
    pa = probA.set_index("method")
    others = [m for m in R.METHODS if m != "lgb"]

    def v(m, op, k, t=a):
        return float(t.loc[(m, op), k])

    def d(name):
        r = c.loc[name]
        return f"{r['difference']:+.3f} [95% CI {r['ci_low_95']:+.3f}, {r['ci_high_95']:+.3f}]"

    def rng(vals):
        lo, hi = (f"{x:.3f}".replace("-0.000", "0.000") for x in (min(vals), max(vals)))
        return lo if lo == hi else f"{lo} to {hi}"

    def cut(m, op):
        g = thr.get_group(m)[f"grade_cutoff_{op}"]
        return f"{g.min():.1f} to {g.max():.1f}"

    prim = con[con.family == "primary"]
    pr_a = {m: v(m, "OP1", "pr_auc") for m in R.METHODS}
    pr_b = {m: v(m, "OP1", "pr_auc", b) for m in R.METHODS}
    pr_nz = {m: v(m, "OP1", "pr_auc", nz) for m in R.METHODS}
    # ---- guards ----------------------------------------------------------------------------------------------
    assert not prim["improves"].any(), "a method met the pre-specified improvement criterion"
    assert max(pr_a, key=pr_a.get) == "classifier" and max(R.METHODS, key=lambda m: v(m, "OP1", "f1")) == "classifier"
    clf = [f"classifier vs lgb (tuned): {k}" for k in R.PRIMARY_METRICS]
    assert all(c.loc[n, "supported_holm_0.05"] and c.loc[n, "difference"] > 0 and not c.loc[n, "practically_important"]
               for n in clf)
    assert c.loc["l1: OP1 vs native rule: recall", "improves"] and c.loc["lgb: OP2 vs native rule: recall", "improves"]
    assert not c.loc["lgb: OP1 vs native rule: recall", "practically_important"]
    gap_native = v("lgb", "native", "recall") - v("l1", "native", "recall")
    gap_op1 = v("lgb", "OP1", "recall") - v("l1", "OP1", "recall")
    assert 0 < gap_op1 < 0.5 * gap_native, "L1's recall deficit is not mainly a threshold effect"
    assert not c.loc["quantile_q25 vs lgb (tuned): pr_auc", "supported_holm_0.05"]
    assert c.loc["weighted vs lgb (tuned): pr_auc", "difference"] < 0 and c.loc["weighted vs lgb (tuned): pr_auc", "supported_holm_0.05"]
    assert all(c.loc[f"{m} vs lgb (tuned): pr_auc", "difference"] < 0 for m in ("l1", "weighted", "ngboost_prob"))
    assert min(pr_a, key=pr_a.get) == "weighted" and min(pr_b, key=pr_b.get) == "weighted"
    assert max(pr_b, key=pr_b.get) == "classifier" and all(pr_b[m] > pr_a[m] for m in R.METHODS)
    assert max(zero_share[(m, "OP1")] for m in R.METHODS) < 0.5
    assert all(pr_nz[m] <= pr_a[m] + 1e-3 for m in R.METHODS)
    assert pa.loc["classifier", "brier_skill_score"] > pa.loc["ngboost_prob", "brier_skill_score"]
    reg_mae = evA["metrics"].dropna(subset=["MAE"]).drop_duplicates("method").set_index("method")["MAE"]
    assert reg_mae["weighted"] > reg_mae["lgb"] + 3

    native_fr = {m: v(m, "native", "flag_rate") for m in R.METHODS}
    op1_rec = {m: v(m, "OP1", "recall") for m in R.METHODS}
    op2_fr = {m: v(m, "OP2", "flag_rate") for m in R.METHODS}
    op2_pr = {m: v(m, "OP2", "precision") for m in R.METHODS}
    zs1 = {m: zero_share[(m, "OP1")] for m in R.METHODS}
    nz_drop = {m: pr_nz[m] - pr_a[m] for m in R.METHODS}
    prev_b = float(evB["metrics"]["prevalence"].iat[0])
    text = f"""<!-- Generated by research/aiesc2027/run_risk.py; design: research/aiesc2027/risk_methods_spec.json -->
### 4.2.1 Follow-up: Risk-Oriented Decision Rules and Training Objectives

To separate the effect of the decision rule and the training objective from the limits of the available information,
an exploratory follow-up with a pre-specified design compared six risk scores built from the same registration-time
features: LightGBM regression with squared (L2) and absolute (L1) loss, a LightGBM classifier for grade < 60, a LightGBM
0.25-quantile regression, a class-weighted L2 regression and NGBoost's P(Y < 60). All models were fitted on 80% of
the students of each training fold; decision thresholds were chosen on the remaining 20% (calibration students) and
applied unchanged to the test fold. Three operating points were compared: each method's native rule (predicted
grade < 60, or recalibrated probability >= 0.5), OP1 (flag as many enrolments as the calibration prevalence of low
grades) and OP2 (the threshold giving recall of at least 0.50 on the calibration students). Table 8 and Figure 7
summarise the results; paired contrasts are in Table S7a.

The native rules flagged very different shares of enrolments ({rng(native_fr.values())}), so recall under the rule
"predicted grade < 60" mainly reflected where each model's predictions were located. For L2 regression the native
rule was already close to the prevalence budget (the OP1 cutoff was a predicted grade of {cut('lgb', 'OP1')}), and
tuning changed recall only slightly ({d('lgb: OP1 vs native rule: recall')}). For L1 regression, whose predictions
are shifted upward, the OP1 cutoff was {cut('l1', 'OP1')} and recall rose from {v('l1', 'native', 'recall'):.3f} to
{v('l1', 'OP1', 'recall'):.3f} ({d('l1: OP1 vs native rule: recall')}). Most of L1's recall deficit in Section 4.2 is
therefore a threshold effect; a smaller ranking deficit remained (PR-AUC {d('l1 vs lgb (tuned): pr_auc')} relative to L2).

At an equal flag budget (OP1), recall ranged from {rng(op1_rec.values())} across methods. The classifier ranked low
grades best (PR-AUC {pr_a['classifier']:.3f} vs {pr_a['lgb']:.3f} for L2 regression, {d('classifier vs lgb (tuned): pr_auc')};
ROC-AUC {v('classifier', 'OP1', 'roc_auc'):.3f} vs {v('lgb', 'OP1', 'roc_auc'):.3f}) and had the highest F1 at OP1
({v('classifier', 'OP1', 'f1'):.3f} vs {v('lgb', 'OP1', 'f1'):.3f}; {d('classifier vs lgb (tuned): f1_OP1')}). These gains
were statistically supported after Holm correction but smaller than the pre-specified practical threshold of 0.05, so
no method met the pre-specified criterion for improving risk identification. The 0.25-quantile model ranked low grades
like L2 regression (PR-AUC {d('quantile_q25 vs lgb (tuned): pr_auc')}). Class weighting harmed both ranking (PR-AUC
{d('weighted vs lgb (tuned): pr_auc')}) and point accuracy (MAE {reg_mae['weighted']:.3f} vs {reg_mae['lgb']:.3f}).
Reaching a recall of 0.50 (OP2) required flagging {rng(op2_fr.values())} of all enrolments, with precision
{rng(op2_pr.values())}; for L2 regression this corresponds to flagging predicted grades below {cut('lgb', 'OP2')}.
After isotonic recalibration on the calibration students, the classifier's probabilities were well calibrated (mean
{pa.loc['classifier', 'mean_probability']:.3f} vs prevalence {pa.loc['classifier', 'prevalence']:.3f}; ECE
{pa.loc['classifier', 'ece_10_bins']:.3f}; Brier skill score {pa.loc['classifier', 'brier_skill_score']:.3f}, compared with
{pa.loc['ngboost_prob', 'brier_skill_score']:.3f} for recalibrated NGBoost). The recall-versus-budget curves of all six
methods nearly overlap (Figure 7a): the decision rule determines where on the curve a model operates, while the
curve itself, and hence the attainable precision for a given recall, is limited by the information available at
registration.

### 4.2.2 Sensitivity Analysis: Including Zero Grades

The main analysis excludes {n_zero:,d} zero grades whose meaning is not recorded. Including them (n = 85,567;
prevalence of grade < 60 {prev_b:.3f}), with every student keeping the fold and calibration role of the main analysis,
the classifier again ranked low grades best (PR-AUC {pr_b['classifier']:.3f}) and class-weighted regression worst
({pr_b['weighted']:.3f}); PR-AUC was higher than in the main analysis for every method ({rng(pr_b.values())}), partly
reflecting the higher base rate. At OP1, {rng(zs1.values())} of the zero-grade enrolments were flagged, so most of them were
not anticipated from registration-time information. Training with the zero grades did not help the remaining
enrolments: evaluated on the same 83,494 non-zero rows, PR-AUC changed by {rng(nz_drop.values())} relative to the
models trained without zeros (Table 9). The conclusions of Sections 4.2 and 4.2.1 therefore do not depend on the
exclusion of zero grades, although an institution that treats zero grades as academic risk would face a larger and
partly unpredictable risk group.

These follow-up analyses reuse the semester analysed throughout this study and are exploratory; they do not
constitute independent validation.
"""
    out.mkdir(parents=True, exist_ok=True)
    (out / "results_en_4_2_1_4_2_2.md").write_text(text, encoding="utf-8")
    key = {"A_metrics": evA["metrics"].to_dict(orient="records"), "contrasts": con.to_dict(orient="records"),
           "B_pr_auc": pr_b, "B_zero_flagged_OP1": zs1, "nonzero_pr_auc_change": nz_drop,
           "classifier_probability": pa.loc["classifier"].to_dict()}
    (out / "key_numbers.json").write_text(json.dumps(key, indent=2, default=float), encoding="utf-8")
